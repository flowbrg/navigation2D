function sigma_r = eval_traj(t, p_x, p_y, p_dx, p_dy, ...
                                p_ddx, p_ddy, p_dddx, p_dddy, Tf)

t = max(0, min(t, Tf));

sigma_r = [polyval(p_x, t), polyval(p_y, t), ...
           polyval(p_dx, t), polyval(p_dy, t), ...
           polyval(p_ddx, t), polyval(p_ddy, t), ...
           polyval(p_dddx, t), polyval(p_dddy, t)];
end